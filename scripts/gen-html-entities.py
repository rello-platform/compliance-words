"""
Generate src/html-entities.ts: the HTML decoder tables maskHtml reads (ruling 297).

Both tables come from Python's standard library, which carries the WHATWG ones:
  - html.entities.html5: the named character reference table (2,231 entries,
    including the 106 legacy names HTML accepts without a semicolon);
  - the cp1252 codec: the numeric remap HTML applies to &#128;-&#159;
    (&#151; renders as an em dash). The five bytes cp1252 leaves undefined keep
    their own code point, as HTML does.

The Python port (python/rate_claims.py) reads the same two stdlib tables
directly, so the TS and Python decoders share one source.

Run:   python3 scripts/gen-html-entities.py          (writes the file)
Check: python3 scripts/gen-html-entities.py --check  (exit 1 when it is stale)
python/test_rate_claims_parity.py runs the check, so `npm test` fails on a stale file.
"""

import html.entities
import json
import os
import sys

_ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(_ROOT, "src", "html-entities.ts")


def numeric_remap():
    out = {}
    for byte in range(0x80, 0xA0):
        try:
            out[byte] = bytes([byte]).decode("cp1252")
        except UnicodeDecodeError:
            continue
    return out


def render():
    named = html.entities.html5
    for name, chars in named.items():
        # maskHtml writes a same-length run; a decode longer than its entity cannot fit.
        if len(chars.encode("utf-16-le")) // 2 > len(name) + 1:
            raise SystemExit("entity &%s decodes longer than itself" % name)
    lines = [
        "// GENERATED by scripts/gen-html-entities.py. Do not edit by hand.",
        "// Source: Python's stdlib html.entities.html5 (the WHATWG named character",
        "// reference table) and the cp1252 codec (the WHATWG numeric remap for",
        "// &#128;-&#159;). Ruling 297. `npm test` fails when this file is stale.",
        "",
        "/** Named character references, keyed without the leading `&`. A key without `;` is a legacy name HTML accepts bare. */",
        "export const HTML_NAMED_ENTITIES: ReadonlyMap<string, string> = new Map<string, string>([",
    ]
    for name in sorted(named):
        lines.append("  [%s, %s]," % (json.dumps(name), json.dumps(named[name])))
    lines.append("]);")
    lines.append("")
    lines.append("/** Numeric references HTML remaps (&#128;-&#159; read as windows-1252). */")
    lines.append("export const HTML_NUMERIC_REMAP: ReadonlyMap<number, string> = new Map<number, string>([")
    for cp, ch in sorted(numeric_remap().items()):
        lines.append("  [0x%x, %s]," % (cp, json.dumps(ch)))
    lines.append("]);")
    lines.append("")
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT, "r", encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != text:
            print("src/html-entities.ts is stale: run python3 scripts/gen-html-entities.py", file=sys.stderr)
            sys.exit(1)
        print("src/html-entities.ts is current (%d named, %d numeric)" % (len(html.entities.html5), len(numeric_remap())))
        return
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
